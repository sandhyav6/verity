// Copies compiled ABIs to backend/app/blockchain/abi so the backend never hand-writes ABIs.
//   npx hardhat compile && npx hardhat run scripts/export-abi.ts
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const camel = (n: string) => n[0].toLowerCase() + n.slice(1);

const names = ["VerityRegistry"];
const outDir = new URL("../../backend/app/blockchain/abi/", import.meta.url);
// Typed (`as const`) copies for viem/wagmi in the frontend, so contract calls are type-checked.
const tsDir = new URL("../../frontend/src/blockchain/abi/", import.meta.url);
mkdirSync(outDir, { recursive: true });
mkdirSync(tsDir, { recursive: true });
for (const n of names) {
  const artifact = JSON.parse(readFileSync(new URL(`../artifacts/contracts/${n}.sol/${n}.json`, import.meta.url), "utf8"));
  writeFileSync(new URL(`${n}.json`, outDir), JSON.stringify(artifact.abi, null, 1));
  writeFileSync(
    new URL(`${camel(n)}Abi.ts`, tsDir),
    `// GENERATED by contracts/scripts/export-abi.ts - do not edit.
export const ${camel(n)}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;
`,
  );
  console.log(`exported ${n} (${artifact.abi.length} entries)`);
}
