"""Independent LMSR reference implementation (50-digit arithmetic) and test-vector generator.

Shares the *mathematical definition* with LMSRMath.sol but none of its code or approximations:
the direct textbook formula C = b * ln(e^(qY/b) + e^(qN/b)) is evaluated with mpmath at 50
digits, so it also cross-checks the contract's overflow-safe log-sum-exp rewrite.

All quantities are integers in wei (1 share = 1 token = 1e18).

Usage:  python reference/lmsr_ref.py   ->  writes reference/vectors.json
Deterministic: fixed seed, no clock or network.
"""

from __future__ import annotations

import json
import random
from pathlib import Path

from mpmath import floor, ceil, exp, log, mp, mpf

mp.dps = 50

WAD = 10**18
LN2 = log(2)
MARGIN_DIVISOR = 10**12


def cost(q_yes: int, q_no: int, b: int) -> mpf:
    """C(qY, qN) in wei, as a high-precision real."""
    return mpf(b) * log(exp(mpf(q_yes) / b) + exp(mpf(q_no) / b))


def price_yes_wad(q_yes: int, q_no: int, b: int) -> mpf:
    """P(YES) * 1e18, as a high-precision real."""
    a, c = exp(mpf(q_yes) / b), exp(mpf(q_no) / b)
    return WAD * a / (a + c)


def margin(b: int) -> int:
    return b // MARGIN_DIVISOR + 1


def point_vectors() -> list[dict]:
    b_values = [10 * WAD, 100 * WAD, 1_000 * WAD, 100_000 * WAD]
    ratios = [  # (qY - qN) / b, spanning the whole allowed range
        0, 0.01, 0.1, 0.5, 1, 2, 5, 10, 15, 19.9, -0.5, -1, -5, -10, -19.9,
    ]
    out = []
    for b in b_values:
        for r in ratios:
            base = 3 * b  # keep both sides positive and non-trivial
            diff = int(r * b)
            q_yes = base + max(diff, 0)
            q_no = base + max(-diff, 0)
            c = cost(q_yes, q_no, b)
            p = price_yes_wad(q_yes, q_no, b)
            out.append(
                {
                    "qYes": str(q_yes),
                    "qNo": str(q_no),
                    "b": str(b),
                    "costFloor": str(int(floor(c))),
                    "costCeil": str(int(ceil(c))),
                    "priceYesWad": str(int(floor(p))),
                }
            )
    # fresh market: C(0,0) = b ln 2, price = 0.5
    for b in b_values:
        out.append(
            {
                "qYes": "0",
                "qNo": "0",
                "b": str(b),
                "costFloor": str(int(floor(cost(0, 0, b)))),
                "costCeil": str(int(ceil(cost(0, 0, b)))),
                "priceYesWad": str(WAD // 2),
            }
        )
    return out


def trade_sequence(seed: int, b: int, steps: int, users: int = 4) -> dict:
    """Valid random buy/sell sequence plus the true cost C(q) after each step."""
    rng = random.Random(seed)
    holdings = [[0, 0] for _ in range(users)]  # [yes, no]
    q = [0, 0]
    ops = []
    for _ in range(steps):
        u = rng.randrange(users)
        side = rng.randrange(2)  # 0 yes, 1 no
        can_sell = holdings[u][side] >= 10**12
        do_sell = can_sell and rng.random() < 0.4
        if do_sell:
            shares = rng.randrange(10**12, holdings[u][side] + 1)
        else:
            shares = rng.randrange(10**12, b // 2)
            nq = list(q)
            nq[side] += shares
            if abs(nq[0] - nq[1]) > 20 * b:
                continue
        if do_sell:
            q[side] -= shares
            holdings[u][side] -= shares
        else:
            q[side] += shares
            holdings[u][side] += shares
        true_c = cost(q[0], q[1], b)
        ops.append(
            {
                "user": u,
                "outcome": side,
                "action": "sell" if do_sell else "buy",
                "shares": str(shares),
                "trueCostCeilAfter": str(int(ceil(true_c))),
                "qYesAfter": str(q[0]),
                "qNoAfter": str(q[1]),
            }
        )
    return {"seed": seed, "b": str(b), "users": users, "ops": ops}


def main() -> None:
    vectors = {
        "meta": {
            "generator": "reference/lmsr_ref.py",
            "precision_digits": mp.dps,
            "note": "All values in wei. Generated by an independent mpmath implementation.",
        },
        "points": point_vectors(),
        "sequences": [
            trade_sequence(seed=1, b=100 * WAD, steps=60),
            trade_sequence(seed=2, b=10 * WAD, steps=60),
            trade_sequence(seed=3, b=100_000 * WAD, steps=60),
        ],
    }
    path = Path(__file__).with_name("vectors.json")
    path.write_text(json.dumps(vectors, indent=1))
    n_ops = sum(len(s["ops"]) for s in vectors["sequences"])
    print(f"wrote {path.name}: {len(vectors['points'])} point vectors, "
          f"{len(vectors['sequences'])} sequences, {n_ops} ops")


if __name__ == "__main__":
    main()
